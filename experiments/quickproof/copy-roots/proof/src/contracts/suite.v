(* ======================================================================
   CONTRACT: every law of the project in one theorem, generated by
   quickproof/tools/new_contract.py.

   Proving `suite` in one worktree makes all laws share one model and one
   specification per function of the code under test.  It needs the proof of
   every theorem in src/contracts/*.v: an Admitted law shows up in
   Print Assumptions of `suite`.
   ====================================================================== *)

Require Import QuickProof.Contract.
Require LeanosRoots.contracts.copy_roots_exact.
Require LeanosRoots.contracts.window_roots_isolated.
Require LeanosRoots.contracts.window_scan_exact.

Theorem suite :
  harness_safe LeanosRoots.contracts.copy_roots_exact.whole_prog /\
  harness_safe LeanosRoots.contracts.window_roots_isolated.whole_prog /\
  harness_safe LeanosRoots.contracts.window_scan_exact.whole_prog.
Proof.
  split; [ | split ].
  - exact LeanosRoots.contracts.copy_roots_exact.copy_roots_exact.
  - exact LeanosRoots.contracts.window_roots_isolated.window_roots_isolated.
  - exact LeanosRoots.contracts.window_scan_exact.window_scan_exact.
Qed.
