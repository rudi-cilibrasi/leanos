(* main, proved under the unit's compspecs (the law's composites are the unit's) for any program without
   global variables (Law2Main.v, from the segment lemmas Law2Seg*.v). *)
Lemma body_main: semax_body nil LeanosRoots.proof.Law2MainDefs.Gmain f_main (_main, main_spec_std p).
Proof. apply M.body_main_gen. vm_compute. reflexivity. Qed.

