(* ======================================================================
   CONTRACT: harness/window_roots_isolated.c, generated by quickproof/tools/new_contract.py.

   The theorem is QuickProof.Contract.harness_safe of the whole program: the
   harness harness/window_roots_isolated.c linked with the units it needs (per-law linking,
   LINK=per-law in quickproof.conf; docs/LINKING.md of the framework):
     patch/roots_unit.c.
   By VST's adequacy theorem, in the honest external world QuickProof.Env: for
   every value the nondet_* functions may return, no execution has undefined
   behaviour; the harness executes undefined behaviour exactly when one of
   its checks fails, so the theorem says its checks hold in every execution.
   What the checks are is written in the harness file.
   ====================================================================== *)

(* THE UNITS (computed, quickproof/tools/link_units.py): the closure of the
   harness under references.  A unit is linked when it defines a global (a
   function with a body, a variable with an initialiser) that a linked unit
   references without defining it, and then with all its definitions.  So
   every global this program references is resolved as in the program of all
   units; the units left out are referenced by no linked unit:
     quickproof/libc/libc.c, quickproof/libc/malloc_unit.c. *)

