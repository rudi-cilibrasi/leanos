   nondet_size_spec; nondet_u32_spec; gp_assert_spec].

Lemma window_roots_isolated_proved : harness_safe whole_prog.
Proof.
  harness_safe_by_specs CS G main_post_TT.
  - reflexivity.
  - entry_shared (semax_body_main_std _ _ p _ _ body_main eq_refl).
    entry_shared H.body_member.
    entry_shared H.body_phys_ok.
    entry_shared H.body_apart.
    entry_shared H.body_table.
    entry_shared LeanosRoots.proof.Law2Tables.body_tables_at.
    entry_shared LeanosRoots.proof.Law2Inventory.body_inventory_ok.
    entry_shared H.body_geometry_ok.
    entry_shared B.body_qotom_root_table_entry.
    entry_shared B.body_qotom_root_phys_ok.
    entry_shared B.body_qotom_root_phys_disjoint.
    entry_shared B.body_qotom_root_protected_frame.
    entry_shared B.body_qotom_root_source_ancestors.
    entry_shared B.body_qotom_build_copy_roots.
    entry_shared B.body_frame_window_pages.
    entry_shared B.body_frame_window_geometry_ok.
    entry_shared B.body_frame_window_root_exact.
    entry_shared B.body_frame_window_build.
    entry_shared B.body_roots_build.
    entry_shared B.body_window_build.
    entry_shared B.body_window_root_exact.
    entry_external (@external_ok_size CS).
    entry_external (@external_ok_u32 CS).
    entry_external (@external_ok_assert CS).
    apply Forall_nil.
Qed.

