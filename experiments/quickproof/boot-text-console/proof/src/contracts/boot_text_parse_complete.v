Lemma round8_int: forall s, 8 <= s <= 64 ->
  Int.and (Int.repr (s + 7)) (Int.not (Int.repr 7)) = Int.repr (round8 s).
Proof.
  intros s Hs. pose proof round8_check as C. rewrite forallb_forall in C.
  specialize (C s). apply Int.same_if_eq. apply C.
  apply in_map_iff. exists (Z.to_nat s). split; [ apply Z2Nat.id; lia | ].
  apply in_seq. lia.
Qed.

