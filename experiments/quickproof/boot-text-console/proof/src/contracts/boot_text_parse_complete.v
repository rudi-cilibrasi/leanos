Lemma byte_int: forall v n, 0 <= v <= Int.max_unsigned -> 0 <= n < 32 ->
  Int.zero_ext 8 (Int.shru (Int.repr v) (Int.repr n)) = Int.repr (v / 2 ^ n mod 256).
Proof.
  intros v n Hv Hn.
  rewrite <- (Int.repr_unsigned (Int.zero_ext 8 _)). rewrite Int.zero_ext_mod by (cbn; lia).
  unfold Int.shru. rewrite (Int.unsigned_repr v) by lia. rewrite (Int.unsigned_repr n) by rep_lia.
  rewrite Z.shiftr_div_pow2 by lia.
  rewrite Int.unsigned_repr.
  - reflexivity.
  - split; [ apply Z.div_pos; [ lia | apply Z.pow_pos_nonneg; lia ] | ].
    apply Z.le_trans with v; [ apply Z.div_le_upper_bound; [ apply Z.pow_pos_nonneg; lia | ] | lia ].
    assert (1 <= 2 ^ n) by (apply Z.pow_le_mono_r with (a := 2) (b := 0) (c := n); lia).
    nia.
Qed.

Lemma u8_addr: forall base n i, field_compatible (tarray tuchar n) [] base -> 0 <= i < n ->
  field_address (tarray tuchar n) [ArraySubsc i] base = offset_val i base.
Proof.
  intros. rewrite field_address_offset.
  - simpl. f_equal. lia.
  - apply field_compatible_cons. simpl. split; [ lia | auto ].
Qed.

Lemma zext_byte: forall b, 0 <= b < 256 -> Int.zero_ext 8 (Int.repr b) = Int.repr b.
Proof.
  intros. rewrite <- (Int.repr_unsigned (Int.zero_ext 8 (Int.repr b))).
  rewrite Int.zero_ext_mod by (cbn; lia).
  rewrite Int.unsigned_repr by rep_lia. change (two_p 8) with 256. rewrite Z.mod_small by lia. reflexivity.
Qed.

