Lemma malloc_test_null (t: type) (q: val) (P: mpred):
  0 <= sizeof t ->
  (if eq_dec q nullval then emp else malloc_token Ews t q * data_at_ Ews t q) * P
  |-- denote_tc_test_eq q (Vlong (Int64.repr 0)).
Proof.
  intros Ht. destruct (eq_dec q nullval).
  - subst. simpl. entailer!.
  - destruct (zlt 0 (sizeof t)).
    + sep_apply (data_at__valid_ptr Ews t q); [ auto | lia | ]. entailer!.
    + sep_apply (malloc_token_valid_pointer Ews t q); [ lia | ]. entailer!.
Qed.

Ltac to_z :=
  repeat match goal with
  | H: context [Int.unsigned (Int.repr ?n)] |- _ => rewrite (Int.unsigned_repr n) in H by rep_lia
  | H: context [Int64.unsigned (Int64.repr ?n)] |- _ => rewrite (Int64.unsigned_repr n) in H by rep_lia
  | H: Int.repr (Z.b2z ?c) = Int.zero |- _ =>
      destruct c eqn:?; [ simpl in H; exfalso; apply Int.one_not_zero; exact H | clear H ]
  | H: Int.repr (Z.b2z ?c) <> Int.zero |- _ =>
      destruct c eqn:?; [ clear H | simpl in H; exfalso; apply H; reflexivity ]
  | H: negb ?c = true |- _ => apply negb_true_iff in H
  | H: negb ?c = false |- _ => apply negb_false_iff in H
  | H: andb ?x ?y = true |- _ => apply andb_prop in H; destruct H
  | H: (?a =? ?b) = true |- _ => apply Z.eqb_eq in H
  | H: (?a =? ?b) = false |- _ => apply Z.eqb_neq in H
  | H: (?a <=? ?b) = true |- _ => apply Z.leb_le in H
  | H: (?a <=? ?b) = false |- _ => apply Z.leb_gt in H
  | H: Int.ltu ?a ?b = true |- _ =>
      unfold Int.ltu in H; match type of H with context [zlt ?x ?y] => destruct (zlt x y); [ clear H | discriminate ] end
  | H: Int.ltu ?a ?b = false |- _ =>
      unfold Int.ltu in H; match type of H with context [zlt ?x ?y] => destruct (zlt x y); [ discriminate | clear H ] end
  end.

(* forward_call's own re-association of the harness's long left-nested sequences stalls; flatten first. *)
Ltac reassoc := repeat match goal with |- semax _ _ (Ssequence (Ssequence _ _) _) _ => rewrite <- seq_assoc end.

Ltac zb :=
  repeat match goal with
  | |- context [?a =? ?b] => first [ rewrite (proj2 (Z.eqb_eq a b)) by lia | rewrite (proj2 (Z.eqb_neq a b)) by lia ]
  | |- context [?a <=? ?b] => first [ rewrite (proj2 (Z.leb_le a b)) by lia | rewrite (proj2 (Z.leb_gt a b)) by lia ]
  end.

(* A branch of an && or ?: that only sets a temporary: its value is the join's. *)
Ltac bclose :=
  entailer!; unfold bool2val;
  repeat match goal with
  | H: ?b = false |- context [?b] => rewrite H
  | H: ?b = true |- context [?b] => rewrite H
  end;
  repeat match goal with
  | |- context [zeq ?a ?b] => destruct (zeq a b)
  | |- context [zlt ?a ?b] => destruct (zlt a b)
  | |- context [Int.ltu ?a ?b] => unfold Int.ltu
  | |- context [Int.unsigned (Int.repr ?n)] => rewrite (Int.unsigned_repr n) by rep_lia
  end; zb; simpl; first [ reflexivity | (exfalso; lia) ].

(* The join of an if that sets _offset and rewrites the buffer from B1 to B2. *)
Ltac join_buf off_v B1 B2 :=
  match goal with |- semax _ (PROPx ?P (LOCALx ?Q (SEPx ?R))) _ _ =>
    let Q' := remove_LOCAL2 constr:(cons (temp _offset off_v) nil) Q in
    match R with context C [K.bytes B1] =>
      let R' := context C [K.bytes B2] in
      forward_if (PROPx P (LOCALx (temp _offset off_v :: Q') (SEPx R')))
    end
  end.

