Lemma shown_range: forall ch, 0 <= ch <= 255 -> 0 <= shown ch <= 126.
Proof.
  intros ch H. unfold shown.
  destruct (ch <? 32) eqn:E1; [ simpl; lia | ].
  destruct (126 <? ch) eqn:E2; simpl; [ lia | ].
  apply Z.ltb_ge in E1. apply Z.ltb_ge in E2. lia.
Qed.

Lemma zext16: forall x, 0 <= x < 65536 -> Int.zero_ext 16 (Int.repr x) = Int.repr x.
Proof.
  intros x H.
  rewrite <- (Int.repr_unsigned (Int.zero_ext 16 (Int.repr x))).
  rewrite Int.zero_ext_mod by (compute; split; congruence).
  rewrite Int.unsigned_repr by rep_lia. change (two_p 16) with 65536.
  rewrite Z.mod_small by lia. reflexivity.
Qed.

Lemma shown_word: forall ch, 0 <= ch <= 255 ->
  Int.zero_ext 16 (Int.zero_ext 16 (Int.or (Int.repr 1792) (Int.repr (shown ch)))) = Int.repr (1792 + shown ch).
Proof.
  intros ch H. pose proof (shown_range ch H) as R.
  assert (Or: Int.or (Int.repr 1792) (Int.repr (shown ch)) = Int.repr (1792 + shown ch)).
  { unfold Int.or. rewrite !Int.unsigned_repr by rep_lia. rewrite Z.lor_comm.
    pose proof (LeanosConsole.proof.Easy.lor_mul (shown ch) 7 8 ltac:(lia) ltac:(change (2 ^ 8) with 256; lia) ltac:(lia)) as L.
    change (7 * 2 ^ 8) with 1792 in L. rewrite L. f_equal. lia. }
  rewrite Or. rewrite !zext16 by lia. reflexivity.
Qed.

Ltac bool_close :=
  unfold Int.lt, Int.ltu in *; rewrite ?Int.signed_repr, ?Int.unsigned_repr by rep_lia;
  repeat match goal with
  | |- context [zlt ?a ?b] => destruct (zlt a b)
  | |- context [Z.ltb ?a ?b] =>
      let E := fresh "E" in destruct (Z.ltb a b) eqn:E; [ apply Z.ltb_lt in E | apply Z.ltb_ge in E ]
  end; simpl; first [ reflexivity | exfalso; lia ].

Ltac shown_close :=
  unfold shown;
  let E := fresh "E" in
  destruct ((_ <? 32) || (126 <? _))%bool eqn:E; simpl in *;
  first [ reflexivity
        | exfalso; match goal with
                   | H: _ <> _ |- _ => apply H; reflexivity
                   | H: Int.repr 1 = _ |- _ => apply Int.one_not_zero; exact H
                   | H: _ = _ |- _ => discriminate H
                   end ].

Ltac if_lt_close :=
  to_z;
  match goal with |- context [if ?c then _ else _] =>
    let E := fresh "E" in destruct c eqn:E;
    [ apply Z.ltb_lt in E | apply Z.ltb_ge in E ];
    first [ reflexivity | exfalso; lia ]
  end.

Ltac cmp_true :=
  entailer!; simpl;
  unfold Int64.ltu, Int.ltu, Int.eq, Int64.eq in *;
  rewrite ?Int64.unsigned_repr, ?Int.unsigned_repr by rep_lia;
  repeat (first [ rewrite if_true by lia | rewrite if_false by lia ]); reflexivity.

