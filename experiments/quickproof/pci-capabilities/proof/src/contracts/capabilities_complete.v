  - reflexivity.
  - entry_shared (semax_body_main_std _ _ p _ _
                    (LeanosCaps.proof.CompMain.body_main p ltac:(vm_compute; reflexivity)) eq_refl).
    entry_shared LeanosCaps.proof.CompRead.body_space_read.
    entry_shared (B.body_pci_capability_finish K.Dev_comp).
    entry_shared (B.body_pci_collect_capabilities K.Dev_comp).
    entry_shared (B.body_caps_collect K.Dev_comp).
    entry_external (@external_ok_u32 CS).
    entry_external (@external_ok_u8 CS).
    entry_external (@external_ok_assume CS).
    entry_external (@external_ok_assert CS).
    apply Forall_nil.
Qed.

