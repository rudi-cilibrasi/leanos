(* The law's specifications: main, the harness's device_read (the read protocol of the law's device) and
   named_pointer, every function of the caps unit at the law's device, and the environment functions the program
   calls. *)
Definition G : funspecs :=
  [(_main, QPmain_spec_ext' p tt main_post_TT);
   A.device_read_spec; A.named_pointer_spec;
   C.finish_spec; C.collect_spec A.Dev_adv; C.caps_collect_spec A.Dev_adv;
   nondet_u8_spec; nondet_u32_spec; gp_assert_spec].

Lemma capabilities_adversarial_proved : harness_safe whole_prog.
Proof.
  harness_safe_by_specs CS G main_post_TT.
  - reflexivity.
  - entry_shared (semax_body_main_std _ _ p _ _
                    (LeanosCaps.proof.AdvMain.body_main p ltac:(vm_compute; reflexivity)) eq_refl).
    entry_shared LeanosCaps.proof.AdvRead.body_device_read.
    entry_shared LeanosCaps.proof.AdvNamed.body_named_pointer.
    entry_shared (B.body_pci_capability_finish A.Dev_adv).
    entry_shared (B.body_pci_collect_capabilities A.Dev_adv).
    entry_shared (B.body_caps_collect A.Dev_adv).
    entry_external (@external_ok_u8 CS).
    entry_external (@external_ok_u32 CS).
    entry_external (@external_ok_assert CS).
    apply Forall_nil.
Qed.

